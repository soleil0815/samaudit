def t(key: str, lang: str = "de", **kw) -> str:
    entry = T.get(key)
    s = (entry.get(lang) or entry.get("de") or key) if entry else key
    if kw:
        try:
            s = s.format(**kw)
        except (KeyError, IndexError):
            pass
    return s


def tv(value, lang: str = "de") -> str:
    """Translates finding values that start with '@'."""
    if isinstance(value, str) and value.startswith("@"):
        key, _, arg = value[1:].partition("|")
        if key in T:
            return t(key, lang, arg=arg) if arg else t(key, lang)
    return "" if value is None else str(value)


def level_key(score: int) -> int:
    if score < 15:
        return 0
    if score < 35:
        return 1
    if score < 60:
        return 2
    return 3
