#!/usr/bin/env bash
# SPDX-License-Identifier: AGPL-3.0-or-later
# Recomputes all pinned versions of the image (needs Docker with buildx and internet access).
#
#   tools/update-locks.sh            security update WITHIN the bounds of tools/lock-policy.env:
#                                    newest Python patch release of the series on the same Debian
#                                    release (tag + digest), today's Debian snapshot, and every Python
#                                    package within its major version (0.x: minor version)
#   tools/update-locks.sh --major    also allow new major versions of Python packages
#                                    (deliberate step, e.g. when lifting the base – never automatic)
#   tools/update-locks.sh --no-build only the input locks, without building the image for
#                                    locks/os-packages.txt
#
# Changes: Dockerfile (ARG PYTHON_IMAGE, ARG DEBIAN_SNAPSHOT), requirements.txt,
#          requirements-dev.txt, locks/os-packages.txt. Review them with "git diff".
if [ -z "${BASH_VERSION:-}" ]; then exec bash "$0" "$@"; fi #
set -euo pipefail
cd "$(dirname "$0")/.."

MAJOR=0; BUILD=1
for a in "$@"; do
  case "$a" in
    --major) MAJOR=1 ;;
    --no-build) BUILD=0 ;;
    -h|--help) sed -n '3,17p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "unknown option: $a" >&2; exit 2 ;;
  esac
done
# shellcheck disable=SC1091
set -a; . tools/lock-policy.env; set +a

work="$(mktemp -d)"; trap 'rm -rf "$work"' EXIT

# 1) base image: newest patch release of the series on the same Debian release, pinned by digest
curl -sSfL --retry 3 -o "$work/library" \
  https://raw.githubusercontent.com/docker-library/official-images/master/library/python
tag="$(python3 tools/lockutil.py pick-base "$work/library" "$PYTHON_SERIES" "$DEBIAN_CODENAME")"
digest="$(docker buildx imagetools inspect "python:$tag" --format '{{json .Manifest}}' \
          | python3 -c 'import json, sys; print(json.load(sys.stdin)["digest"])')"
[[ "$digest" =~ ^sha256:[0-9a-f]{64}$ ]] || { echo "cannot determine digest of python:$tag" >&2; exit 1; }
image="python:$tag@$digest"
echo "base image:      $image"

# 2) Debian packages: state of snapshot.debian.org at the start of today (UTC)
snapshot="$(date -u +%Y%m%dT000000Z)"
echo "Debian snapshot: $snapshot"

# 3) Python packages: resolve inside the new base image (same Python version as at runtime)
cp requirements.txt "$work/old-requirements.txt" 2>/dev/null || : > "$work/old-requirements.txt"
if [ "$MAJOR" = 1 ]; then : > "$work/constraints.txt"
else python3 tools/lockutil.py constraints "$work/old-requirements.txt" > "$work/constraints.txt"
fi
cp requirements-dev.txt "$work/old-dev.txt" 2>/dev/null || : > "$work/old-dev.txt"
if [ "$MAJOR" = 1 ]; then : > "$work/constraints-dev.txt"
else python3 tools/lockutil.py constraints "$work/old-dev.txt" > "$work/constraints-dev.txt"
fi
docker run --rm -e PIP_VERSION -e PIP_TOOLS_VERSION \
  -v "$PWD:/src:ro" -v "$work:/work" "$image" sh -eu -c '
    python -m venv /tmp/v
    /tmp/v/bin/pip install -q --disable-pip-version-check "pip==$PIP_VERSION" "pip-tools==$PIP_TOOLS_VERSION"
    cd /src
    for f in "" "-dev"; do
      /tmp/v/bin/pip-compile -q --no-header --generate-hashes --allow-unsafe --strip-extras \
        --no-emit-index-url --upgrade --resolver=backtracking \
        -c "/work/constraints$f.txt" -o "/work/requirements$f.txt" "requirements$f.in"
    done'
{
  echo "# SAMAUDIT – lock file: every Python package of the image with exact version and hashes."
  echo "# Generated by tools/update-locks.sh from requirements.in (Python $tag) – do not edit by hand."
  cat "$work/requirements.txt"
} > "$work/requirements.final"
{
  echo "# Test-only lock file (CI self-tests). Generated by tools/update-locks.sh from requirements-dev.in."
  cat "$work/requirements-dev.txt"
} > "$work/requirements-dev.final"

# 4) never leave the bounds silently
if [ "$MAJOR" = 0 ]; then
  python3 tools/lockutil.py check-bounds "$work/old-requirements.txt" "$work/requirements.final" \
    || { echo "lock update would leave the version bounds (see above) – aborted" >&2; exit 1; }
fi

# 5) write the results
mv "$work/requirements.final" requirements.txt
mv "$work/requirements-dev.final" requirements-dev.txt
sed -i -e "s#^ARG PYTHON_IMAGE=.*#ARG PYTHON_IMAGE=$image#" \
       -e "s#^ARG DEBIAN_SNAPSHOT=.*#ARG DEBIAN_SNAPSHOT=$snapshot#" \
       -e "s#^ARG DEBIAN_CODENAME=.*#ARG DEBIAN_CODENAME=$DEBIAN_CODENAME#" Dockerfile

# 6) build without cache and record the resulting Debian package list
if [ "$BUILD" = 1 ]; then
  docker build --no-cache --pull -t samaudit:candidate . >&2
  mkdir -p locks
  docker run --rm --entrypoint cat samaudit:candidate /app/os-packages.txt > locks/os-packages.txt
  echo "Debian packages: $(wc -l < locks/os-packages.txt) recorded in locks/os-packages.txt"
fi
echo "done – review with: git diff"
